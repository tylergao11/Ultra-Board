def main() -> int:
    ok, fail = [], []
    for day, stories in DAYS.items():
        try:
            path = write_day(day, stories)
            # summarize mapping
            data = json.loads(path.read_text(encoding="utf-8"))
            matched = unresolved = 0
            bad = []
            for s in data["stories"]:
                for st in s.get("stocks") or []:
                    if st.get("mapping_status") == "matched_same_day_stock":
                        matched += 1
                    else:
                        unresolved += 1
                        bad.append(f"{st.get('name')}:{st.get('mapping_status')}")
                    if not st.get("name") or st.get("name") in ("x", "X"):
                        bad.append(f"empty-name in {s.get('context')}")
                    if st.get("story") in ("涨停复盘归类待核", ""):
                        bad.append(f"bad-story {st.get('name')}")
            print(f"{day}: wrote stories={len(stories)} matched={matched} unresolved={unresolved}")
            if bad:
                print("  unresolved/bad:", "; ".join(bad[:20]))
            ok.append(day)
        except Exception as e:
            print(f"{day}: FAIL {e}")
            fail.append(day)
    print("DONE ok=", ok)
    print("FAIL=", fail)
    return 0 if not fail else 1


if __name__ == "__main__":
    raise SystemExit(main())
