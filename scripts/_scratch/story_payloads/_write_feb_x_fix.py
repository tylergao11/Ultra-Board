"""Rewrite name=x for selected Feb days from strong_wind PNGs + limit_pool."""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = Path(__file__).resolve().parent
WRITE = ROOT / "tools" / "write_story_day.py"


def pool_map(day: str) -> dict[str, str]:
    path = ROOT / "data" / "ths" / "limit_pool" / f"{day}.json"
    code_to_name: dict[str, str] = {}
    name_to_code: dict[str, str] = {}
    data = json.loads(path.read_text(encoding="utf-8-sig"))
    for row in data.get("stocks") or []:
        code = str(row.get("code") or "").zfill(6)
        name = str(row.get("name") or "").strip()
        if code.isdigit() and name:
            code_to_name[code] = name
            name_to_code[name] = code
    return code_to_name, name_to_code


def S(code_to_name, name_to_code, code: str, name: str, story: str) -> dict:
    code = str(code).zfill(6) if code else ""
    # prefer code from pool; fall back to name
    if code and code in code_to_name:
        name = code_to_name[code]
    elif name in name_to_code:
        code = name_to_code[name]
    return {"code": code or None, "name": name, "story": story}


def build_day(day: str, stories: list) -> Path:
    code_to_name, name_to_code = pool_map(day)
    payload_stories = []
    for ctx, story, stocks in stories:
        out_stocks = []
        for code, name, st in stocks:
            out_stocks.append(S(code_to_name, name_to_code, code, name, st))
        payload_stories.append({"context": ctx, "story": story, "stocks": out_stocks})
    payload = {"stories": payload_stories}
    path = OUT / f"{day}.json"
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return path


