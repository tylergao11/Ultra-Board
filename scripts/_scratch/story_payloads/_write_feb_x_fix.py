def main() -> int:
    days = list(DAYS.keys())
    for day in days:
        path = build_day(day, DAYS[day])
        # verify all codes resolve
        code_to_name, name_to_code = pool_map(day)
        payload = json.loads(path.read_text(encoding="utf-8"))
        bad = []
        for s in payload["stories"]:
            for st in s["stocks"]:
                c, n = st.get("code"), st["name"]
                if not c or c not in code_to_name:
                    bad.append((s["context"], n, c))
                elif code_to_name[c] != n:
                    bad.append((s["context"], f"{n}!={code_to_name[c]}", c))
        nstocks = sum(len(s["stocks"]) for s in payload["stories"])
        print(f"{day}: stories={len(payload['stories'])} stocks={nstocks} bad={len(bad)}")
        for b in bad:
            print("  BAD", b)
        if bad:
            return 1
        r = subprocess.run(
            [sys.executable, str(WRITE), day, "--payload", str(path)],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            encoding="utf-8",
        )
        print(r.stdout.strip() or r.stderr.strip())
        if r.returncode != 0:
            print(r.stderr)
            return r.returncode
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
